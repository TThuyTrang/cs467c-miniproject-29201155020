"""Check the local environment using disposable synthetic text only."""

from __future__ import annotations

import importlib
from importlib.metadata import version
import os
from pathlib import Path
import struct
import sys
import tempfile


ROOT = Path(__file__).resolve().parent


def main() -> int:
    expected_python = ROOT / ".venv" / "Scripts" / "python.exe"
    if sys.version_info[:2] != (3, 11):
        raise RuntimeError(f"Python 3.11 is required; found {sys.version.split()[0]}")
    if struct.calcsize("P") * 8 != 64:
        raise RuntimeError("64-bit Python is required")
    if Path(sys.executable).resolve() != expected_python.resolve():
        raise RuntimeError(f"Run this script with {expected_python}")
    if sys.prefix == sys.base_prefix or Path(sys.prefix).resolve() != (ROOT / ".venv").resolve():
        raise RuntimeError("The project .venv is not active")

    print(f"Python: {sys.version.split()[0]} (64-bit)")
    print(f"Executable: {sys.executable}")

    # Keep any Matplotlib configuration/cache generated by this check local.
    os.environ["MPLCONFIGDIR"] = str(ROOT / ".cache" / "matplotlib")
    packages = {
        "numpy": "numpy",
        "pandas": "pandas",
        "scikit-learn": "sklearn",
        "scipy": "scipy",
        "matplotlib": "matplotlib",
        "nltk": "nltk",
        # Jupyter is a metapackage; jupyter_core provides its importable runtime.
        "jupyter": "jupyter_core",
        "joblib": "joblib",
    }
    for distribution, module in packages.items():
        importlib.import_module(module)
        print(f"[OK] {distribution}=={version(distribution)} (import {module})")

    import joblib
    import numpy as np
    from sklearn.feature_extraction.text import TfidfVectorizer

    scratch = ROOT / ".tmp"
    scratch.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="environment-check-", dir=scratch) as temporary:
        temporary_path = Path(temporary)
        artifact = temporary_path / "tfidf-check.joblib"
        # This is an environment smoke check, not a project dataset/model.
        documents = ["temporary alpha beta", "temporary beta gamma"]
        vectorizer = TfidfVectorizer()
        original = vectorizer.fit_transform(documents)
        joblib.dump(vectorizer, artifact)
        if not artifact.is_file() or artifact.stat().st_size == 0:
            raise RuntimeError("joblib did not save the fitted vectorizer")
        restored = joblib.load(artifact)
        if restored.vocabulary_ != vectorizer.vocabulary_:
            raise RuntimeError("Vectorizer vocabulary changed after serialization")
        np.testing.assert_allclose(restored.transform(documents).toarray(), original.toarray())
    if temporary_path.exists():
        raise RuntimeError(f"Temporary test directory was not removed: {temporary_path}")
    print("[OK] TF-IDF fit/transform and joblib save/load; temporary files removed")
    print("Environment check passed.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        sys.exit(1)
